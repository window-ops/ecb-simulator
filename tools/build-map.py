"""Builds js/data/map.js, the map of Europe, from Natural Earth.

Natural Earth's 1:50m countries (public domain) are projected with the
Lambert azimuthal equal-area projection centered on 52 N, 10 E (the
projection of EPSG:3035, used by Eurostat), clipped to Europe, simplified to
about 4 km and written as SVG paths on a 1000-unit-wide canvas.

    curl -O https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson
    pip install shapely
    python3 tools/build-map.py ne_50m_admin_0_countries.geojson [ne_50m_admin_0_map_units.geojson]

The optional second file, Natural Earth's 1:50m map units, adds Scotland as
an outline of its own (code SCT, part of GB), for runs that assume its
independence; the map draws it only then (js/ui/map.js, S.mapShapes).
"""
import json
import math
import sys

from shapely.geometry import box, shape
from shapely.ops import transform

LAT0, LON0, R = math.radians(52), math.radians(10), 6371.0
X0, X1, Y0, Y1 = -2600, 2900, -2300, 2350
W = 1000.0
SCALE = W / (X1 - X0)
SKIP = {"AD", "SM", "LI", "JE", "GG", "IM", "VA", "MC"}
MERGE = {"AX": "FI"}

def laea(lon, lat):
    lon, lat = math.radians(lon), math.radians(lat)
    k = math.sqrt(2 / (1 + math.sin(LAT0) * math.sin(lat) + math.cos(LAT0) * math.cos(lat) * math.cos(lon - LON0)))
    return (R * k * math.cos(lat) * math.sin(lon - LON0),
            R * k * (math.cos(LAT0) * math.sin(lat) - math.sin(LAT0) * math.cos(lat) * math.cos(lon - LON0)))

def project(geom):
    return transform(lambda xs, ys, zs=None: tuple(zip(*[laea(a, b) for a, b in zip(xs, ys)])), geom)

def ring(r):
    pts = [((x - X0) * SCALE, (Y1 - y) * SCALE) for x, y in r.coords]
    return "M" + "L".join("%.1f %.1f" % p for p in pts) + "Z"

def main(src, units=None):
    data = json.load(open(src))
    clip = box(X0, Y0, X1, Y1)
    shapes = {}
    areas = {}
    feats = data["features"]
    if units:
        for f in json.load(open(units))["features"]:
            if f["properties"].get("GU_A3") == "SCT":
                f["properties"]["ISO_A2_EH"] = "SCT"
                f["properties"]["PART_OF"] = "GB"
                feats = feats + [f]
    for f in feats:
        p = f["properties"]
        g = shape(f["geometry"])
        minx, miny, maxx, maxy = g.bounds
        if maxx < -30 or minx > 60 or maxy < 25 or miny > 75:
            continue
        code = p.get("ISO_A2_EH") or p.get("ISO_A2")
        if code in SKIP:
            continue
        code = MERGE.get(code, code)
        name = p["NAME"]
        pg = project(g).buffer(0).intersection(clip)
        if pg.is_empty:
            continue
        pg = pg.simplify(4.0, preserve_topology=True)
        polys = [pg] if pg.geom_type == "Polygon" else [q for q in getattr(pg, "geoms", []) if q.geom_type == "Polygon"]
        polys = [q for q in polys if q.area >= 8]
        if not polys:
            continue
        path = "".join(ring(q.exterior) + "".join(ring(i) for i in q.interiors) for q in polys)
        main = max(polys, key=lambda q: q.area)
        big = main.representative_point()
        if code == "-99":
            code = "XX" + str(len(shapes))
        label = {"cx": round((big.x - X0) * SCALE, 1), "cy": round((Y1 - big.y) * SCALE, 1)}
        if code in shapes:
            shapes[code]["d"] += path
            if main.area > areas[code]:
                shapes[code].update(label)
                shapes[code]["name"] = name
                areas[code] = main.area
            continue
        areas[code] = main.area
        shapes[code] = dict({"code": code, "name": name, "d": path}, **label)
        if p.get("PART_OF"):
            shapes[code]["part"] = p["PART_OF"]
    out = {"w": W, "h": round((Y1 - Y0) * SCALE, 1), "shapes": list(shapes.values())}
    js = ("/* The map of Europe: country outlines from Natural Earth, 1:50m\n"
          "   (public domain, licenses/natural-earth.txt), projected with the\n"
          "   Lambert azimuthal equal-area projection of EPSG:3035. Generated by\n"
          "   tools/build-map.py; do not edit by hand. */\n"
          "window.ECBSIM = window.ECBSIM || {};\nECBSIM.MAP = " + json.dumps(out, separators=(",", ":")) + ";\n")
    open("js/data/map.js", "w").write(js)
    print(len(out["shapes"]), "shapes")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
